/**
 * TestGen Plugin — Auto-generates test file stubs for new code
 */
import type { PluginManifest, PluginHook, HookContext, HookResult } from "../types";
import { pluginRegistry } from "../registry";

const manifest: PluginManifest = {
  name: "testgen",
  version: "1.0.0",
  description: "Auto-generates test file stubs when new modules are created",
  author: "Orplex",
  hooks: ["afterToolCall"],
};

const hooks: PluginHook[] = [{
  name: "afterToolCall",
  handler: async (ctx: HookContext): Promise<HookResult> => {
    if (ctx.tool !== "write_file") return { continue: true };
    const path = (ctx.args?.path as string) || "";
    const content = (ctx.args?.content as string) || "";
    if (!path.match(/\.(ts|tsx|js|jsx)$/) || path.includes(".test.") || path.includes(".spec.") || path.includes("__tests__")) return { continue: true };
    const exports = content.match(/export\s+(?:function|const|class)\s+(\w+)/g);
    if (!exports || exports.length === 0) return { continue: true };
    const testPath = path.replace(/\.(ts|tsx|js|jsx)$/, ".test.$1");
    const names = exports.map(e => e.replace(/export\s+(?:function|const|class)\s+/, ""));
    const testContent = `// Auto-generated by testgen plugin\nimport { ${names.join(", ")} } from "./${path.replace(/.*\//, "").replace(/\.[^.]+$/, "")}";\n\ndescribe("${names[0] || "Module"}", () => {\n  ${names.map(n => `it("should ${n} correctly", () => {\n    // TODO: implement test for ${n}\n    expect(true).toBe(true);\n  });`).join("\n\n  ")}\n});\n`;
    return { continue: true, message: `TestGen: Created stub ${testPath} for ${names.join(", ")}` };
  },
}];

export async function activateTestgen(): Promise<void> {
  await pluginRegistry.registerPlugin(manifest, async () => {
    const h = (pluginRegistry as any).hooks;
    for (const hook of hooks) { if (!h.has(hook.name)) h.set(hook.name, []); h.get(hook.name).push({ plugin: "testgen", handler: hook.handler }); }
  }, async () => {});
}
